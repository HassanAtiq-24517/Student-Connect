-- StudentConnect / DBProject PostgreSQL schema
-- Cross-checked against the DAOs/POJOs/RowMappers in the Spring Boot backend
-- and the original DBMS project report's DDL.

BEGIN;

-- ============================================================
-- Core student/course data
-- ============================================================

CREATE TABLE IF NOT EXISTS students (
    erp         INTEGER PRIMARY KEY,
    program     VARCHAR(255) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    father_name VARCHAR(255) NOT NULL,
    cnic        VARCHAR(32) NOT NULL,
    dob         DATE NOT NULL,
    cgpa        NUMERIC(4,2) NOT NULL
                CHECK (cgpa >= 0 AND cgpa <= 4.00)
);

CREATE TABLE IF NOT EXISTS courses (
    course_code  VARCHAR(32) PRIMARY KEY
                 CHECK (course_code ~ '^[A-Z]{3}-[0-9]{3}$'),
    course_title VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS studentcourses (
    erp         INTEGER NOT NULL,
    course_code VARCHAR(32) NOT NULL,
    term        VARCHAR(32) NOT NULL
                CHECK (term ~ '^(Fall|Spring|Summer) [0-9]{4}$'),
    grade       VARCHAR(8)
                CHECK (grade IN ('A','A-','B+','B','B-','C+','C','C-','F','W')),

    PRIMARY KEY (erp, course_code),

    CONSTRAINT fk_studentcourses_student
        FOREIGN KEY (erp)
        REFERENCES students (erp)
        ON DELETE CASCADE,

    CONSTRAINT fk_studentcourses_course
        FOREIGN KEY (course_code)
        REFERENCES courses (course_code)
        ON DELETE RESTRICT
);

-- ============================================================
-- Authentication
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    erp      INTEGER PRIMARY KEY,
    email    VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,

    CONSTRAINT fk_users_student
        FOREIGN KEY (erp)
        REFERENCES students (erp)
        ON DELETE CASCADE
);

-- ============================================================
-- Learning / mentoring
-- ============================================================

CREATE TABLE IF NOT EXISTS learningrequests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    erp         INTEGER NOT NULL,
    course_code VARCHAR(32) NOT NULL,
    content     TEXT,

    CONSTRAINT fk_learningrequests_student
        FOREIGN KEY (erp)
        REFERENCES students (erp)
        ON DELETE CASCADE,

    CONSTRAINT fk_learningrequests_course
        FOREIGN KEY (course_code)
        REFERENCES courses (course_code)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_learningrequests_erp
    ON learningrequests (erp);

CREATE INDEX IF NOT EXISTS idx_learningrequests_course_code
    ON learningrequests (course_code);

-- A mentor record represents a student (erp) accepting a particular
-- learning request (id). PK is "id" ALONE (not composite with erp) --
-- this is what enforces the One-to-One rule between a LearningRequest
-- and its MentorRecord: a request can only ever be accepted once.
CREATE TABLE IF NOT EXISTS mentor_records (
    id  BIGINT PRIMARY KEY,
    erp INTEGER NOT NULL,

    CONSTRAINT fk_mentor_records_request
        FOREIGN KEY (id)
        REFERENCES learningrequests (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_mentor_records_student
        FOREIGN KEY (erp)
        REFERENCES students (erp)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_mentor_records_erp
    ON mentor_records (erp);

-- ============================================================
-- Project groups
-- ============================================================

CREATE TABLE IF NOT EXISTS projectgroups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    size        INTEGER NOT NULL CHECK (size >= 2 AND size <= 5),
    course_code VARCHAR(32) NOT NULL,

    CONSTRAINT fk_projectgroups_course
        FOREIGN KEY (course_code)
        REFERENCES courses (course_code)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_projectgroups_course_code
    ON projectgroups (course_code);

-- Membership table for students in project groups.
CREATE TABLE IF NOT EXISTS studentgroups (
    erp      INTEGER NOT NULL,
    group_id BIGINT NOT NULL,

    PRIMARY KEY (erp, group_id),

    CONSTRAINT fk_studentgroups_student
        FOREIGN KEY (erp)
        REFERENCES students (erp)
        ON DELETE CASCADE,

    CONSTRAINT fk_studentgroups_group
        FOREIGN KEY (group_id)
        REFERENCES projectgroups (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_studentgroups_group_id
    ON studentgroups (group_id);

COMMIT;
